// Builds CSS custom properties from the Flux DS Figma export.
// Input:  tokens/figma-export.json  (variables, text styles, effect styles)
// Output: src/styles/tokens.css     (one CSS variable per Figma variable, aliases kept as var())
//         src/styles/typography.css (one class per text style)
//         src/tokens.generated.ts   (token list, used by the Foundations page)
// Run with: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../tokens/figma-export.json', import.meta.url)));

const cssName = (name) => '--' + name.toLowerCase().replace(/[\/\s]+/g, '-');
const isRef = (v) => v && typeof v === 'object' && 'ref' in v;
const unitless = (name) => /(^|\/)(opacity|weight)$/.test(name);

const known = new Set(src.variables.map(([, name]) => name));
const lines = [];
const list = [];
let currentCollection = '';

for (const [collection, name, value] of src.variables) {
  if (collection !== currentCollection) {
    lines.push(`\n  /* ${collection} */`);
    currentCollection = collection;
  }
  let css;
  if (isRef(value)) {
    if (!known.has(value.ref)) throw new Error(`Unknown alias ${value.ref} in ${name}`);
    css = `var(${cssName(value.ref)})`;
  } else if (typeof value === 'number') {
    css = unitless(name) ? String(value) : `${value}px`;
  } else {
    css = value;
  }
  lines.push(`  ${cssName(name)}: ${css};`);
  list.push({ collection, name, css: cssName(name), alias: isRef(value) ? value.ref : null, raw: isRef(value) ? null : value });
}

for (const [name, value] of src.effectStyles) {
  lines.push(`  ${cssName('shadow/' + name)}: ${value};`);
}

const header = `/* Generated by scripts/build-tokens.mjs from tokens/figma-export.json — do not edit by hand. */\n`;
mkdirSync(new URL('../src/styles/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), `${header}:root {${lines.join('\n')}\n}\n`);

const weights = { Regular: 400, SemiBold: 600, Bold: 700 };
const type = src.textStyles.map(([name, weight, size, lineHeight, letterSpacing]) => {
  const cls = '.' + name.replace(/^paragraph\//, '').replace(/^heading\//, '').replace(/\//g, '-');
  return `${cls} {\n  font-family: var(--font-family);\n  font-weight: ${weights[weight]};\n  font-size: ${size}px;\n  line-height: ${lineHeight}px;${letterSpacing ? `\n  letter-spacing: ${letterSpacing};` : ''}\n}`;
});
writeFileSync(
  new URL('../src/styles/typography.css', import.meta.url),
  `${header}:root {\n  --font-family: 'Lexend', system-ui, sans-serif;\n}\n\n${type.join('\n\n')}\n`
);

const typeList = src.textStyles.map(([name, weight, size, lineHeight]) => ({
  name,
  className: name.replace(/^paragraph\//, '').replace(/^heading\//, '').replace(/\//g, '-'),
  weight,
  size,
  lineHeight,
}));
writeFileSync(
  new URL('../src/tokens.generated.ts', import.meta.url),
  `// Generated by scripts/build-tokens.mjs — do not edit by hand.\n` +
    `export const tokens = ${JSON.stringify(list, null, 2)} as const;\n\n` +
    `export const textStyles = ${JSON.stringify(typeList, null, 2)} as const;\n`
);

console.log(`✔ ${list.length} variables, ${typeList.length} text styles, ${src.effectStyles.length} effect styles`);
